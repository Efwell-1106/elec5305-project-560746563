        fprintf("Analyzing: %s\n", filename);

        result = analyzeAudio(filename);

        newRow = table( ...
            string(prompt), ...
            seed, ...
            result.centroid, ...
            result.slope, ...
            result.hfRatio, ...
            result.rms, ...
            result.pitch, ...
            result.onsetRate, ...
            result.spectralFlux, ...
            'VariableNames', { ...
            'Prompt', ...
