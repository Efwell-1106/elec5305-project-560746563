%% =========================================================
% Calculate relative changes from Neutral
% =========================================================

features = [ ...
    "Centroid", ...
    "Slope", ...
    "HFRatio", ...
    "RMS", ...
    "Pitch", ...
    "OnsetRate", ...
    "SpectralFlux"];


relativeDark = zeros(length(seeds), length(features));

relativeBright = zeros(length(seeds), length(features));


for s = 1:length(seeds)

    seed = seeds(s);

    darkRow = results( ...
        results.Prompt == "Dark" & ...
        results.Seed == seed, :);

    neutralRow = results( ...
        results.Prompt == "Neutral" & ...
        results.Seed == seed, :);

    brightRow = results( ...
        results.Prompt == "Bright" & ...
        results.Seed == seed, :);


    for f = 1:length(features)

        featureName = features(f);

        neutralValue = neutralRow.(featureName);

        relativeDark(s,f) = ...
            (darkRow.(featureName) - neutralValue) ...
            / neutralValue * 100;

        relativeBright(s,f) = ...
            (brightRow.(featureName) - neutralValue) ...
            / neutralValue * 100;

    end

end


darkMean = mean(relativeDark, 1);

brightMean = mean(relativeBright, 1);

darkSD = std(relativeDark, 0, 1);

brightSD = std(relativeBright, 0, 1);


%% =========================================================
% FIGURE 1
% =========================================================

figureSeed = 12335;

darkFile = fullfile( ...
    baseFolder, ...
    "Dark", ...
    "Dark_" + figureSeed + ".wav");

neutralFile = fullfile( ...
    baseFolder, ...
    "Neutral", ...
    "Neutral_" + figureSeed + ".wav");

brightFile = fullfile( ...
    baseFolder, ...
    "Bright", ...
    "Bright_" + figureSeed + ".wav");


[darkAudio, Fs] = audioread(darkFile);

[neutralAudio, ~] = audioread(neutralFile);

[brightAudio, ~] = audioread(brightFile);


if size(darkAudio,2) > 1
    darkAudio = mean(darkAudio,2);
end

if size(neutralAudio,2) > 1
    neutralAudio = mean(neutralAudio,2);
end

if size(brightAudio,2) > 1
    brightAudio = mean(brightAudio,2);
end


windowLength = round(0.020 * Fs);

hopLength = round(0.004 * Fs);

nfft = 4096;

window = hamming(windowLength);


[Sdark, F, ~] = spectrogram( ...
    darkAudio, ...
    window, ...
    windowLength-hopLength, ...
    nfft, ...
    Fs);

[Sneutral, ~, ~] = spectrogram( ...
    neutralAudio, ...
    window, ...
    windowLength-hopLength, ...
    nfft, ...
    Fs);

[Sbright, ~, ~] = spectrogram( ...
    brightAudio, ...
    window, ...
    windowLength-hopLength, ...
    nfft, ...
    Fs);


darkSpectrum = 20 * log10(abs(Sdark) + eps);

neutralSpectrum = 20 * log10(abs(Sneutral) + eps);

brightSpectrum = 20 * log10(abs(Sbright) + eps);


darkMeanSpectrum = mean(darkSpectrum,2);

neutralMeanSpectrum = mean(neutralSpectrum,2);

brightMeanSpectrum = mean(brightSpectrum,2);


freqIndex = F <= 10000;


figure;

plot( ...
    F(freqIndex), ...
    darkMeanSpectrum(freqIndex), ...
    'LineWidth',1.5);

hold on;

plot( ...
    F(freqIndex), ...
    neutralMeanSpectrum(freqIndex), ...
    'LineWidth',1.5);

plot( ...
    F(freqIndex), ...
    brightMeanSpectrum(freqIndex), ...
    'LineWidth',1.5);

xline(4000,'--');

hold off;


xlabel('Frequency (Hz)');

ylabel('Magnitude (dB)');

title('Figure 1: Matched Dark / Neutral / Bright Spectra');

legend( ...
    'Dark', ...
    'Neutral', ...
    'Bright', ...
    '4 kHz HF boundary', ...
    'Location','best');

grid on;

xlim([0 10000]);


darkFigure1 = results( ...
    results.Prompt == "Dark" & ...
    results.Seed == figureSeed,:);

neutralFigure1 = results( ...
    results.Prompt == "Neutral" & ...
    results.Seed == figureSeed,:);

brightFigure1 = results( ...
    results.Prompt == "Bright" & ...
    results.Seed == figureSeed,:);


featureText = sprintf([ ...
    'Seed = %d\n\n' ...
    'Dark:\n' ...
    'Centroid = %.1f Hz\n' ...
    'Slope = %.5f\n' ...
    'HF Ratio = %.4f\n\n' ...
    'Neutral:\n' ...
    'Centroid = %.1f Hz\n' ...
    'Slope = %.5f\n' ...
    'HF Ratio =%.4f\n\n' ...
    'Bright:\n' ...
    'Centroid = %.1f Hz\n' ...
    'Slope = %.5f\n' ...
    'HF Ratio = %.4f'], ...
    figureSeed, ...
    darkFigure1.Centroid, ...
    darkFigure1.Slope, ...
    darkFigure1.HFRatio, ...
    neutralFigure1.Centroid, ...
    neutralFigure1.Slope, ...
    neutralFigure1.HFRatio, ...
    brightFigure1.Centroid, ...
    brightFigure1.Slope, ...
    brightFigure1.HFRatio);


